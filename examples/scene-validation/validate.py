"""Small rigid-contact comparison. Synthetic references test tooling, not real-to-sim accuracy."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw

from world_use.bodies.mujoco_scene import mj
from world_use.cameras import View
from world_use.scene_validation import Observation, Validation, fit_camera, scene_identity
from world_use.tasks import json_bytes, write_new

HERE = Path(__file__).resolve().parent
LIMITS = dict(landmark_px=2.0, geometry_m=0.001, motion_m=0.003, penetration_m=0.001,
              support_m=0.001, drift_m=0.0005)
POINTS = np.array([[x, y, z] for x in (-0.12, 0.12) for y in (-0.10, 0.10) for z in (0.03, 0.15)])


def slide(dimensions, friction, velocity):
    """Free sliding after an impulse; both contacting geoms use the declared friction."""
    half = np.asarray(dimensions) / 2
    model = mj.MjModel.from_xml_string(f"""<mujoco>
      <option timestep="0.001" integrator="implicitfast" cone="elliptic" iterations="100"/>
      <default><geom friction="{friction} 0.001 0.00001" condim="3" solref="0.005 1"/></default>
      <worldbody><geom type="plane" size="1 1 .01"/>
        <body pos="0 0 {half[2]}"><freejoint/>
          <geom type="box" size="{' '.join(map(str, half))}" mass="0.1"/>
        </body>
      </worldbody></mujoco>""")
    data = mj.MjData(model)
    # Establish support before the impulse, without using the reference trajectory.
    for _ in range(300):
        mj.mj_step(model, data)
    data.time = 0
    data.qvel[0] = velocity
    samples, states, penetration = [], [], []
    for _ in range(1001):
        samples.append([data.time, *data.qpos[:3]])
        states.append(np.r_[data.qpos, data.qvel])
        penetration.append(max((max(0, -data.contact[i].dist) for i in range(data.ncon)), default=0))
        mj.mj_step(model, data)
    return np.array(samples), dict(state=np.array(states), penetration_m=penetration,
                                  support_error_m=np.array(samples)[:, 3] - half[2],
                                  rest_xyz_m=np.array(samples)[800:, 1:4])


def projection(view, points):
    """A labelled projection fixture, deliberately not a photorealistic appearance reference."""
    image = Image.new("RGB", (view.width, view.height), "#f0eee7")
    draw = ImageDraw.Draw(image)
    pixels, depth = view.project(points)
    for index, (point, z) in enumerate(zip(pixels, depth, strict=True)):
        if z > 0:
            x, y = point
            draw.ellipse((x - 4, y - 4, x + 4, y + 4), fill="#164e74")
            draw.text((x + 5, y - 5), str(index), fill="#164e74")
    draw.text((10, view.height - 20), "SYNTHETIC LANDMARK PROJECTION", fill="black")
    return image


def generate_reference(output):
    """Independent ideal Coulomb model supplies synthetic observations at two initial velocities."""
    view = View.look_at([0.4, -0.5, 0.6], [0, 0, 0.1], size=(480, 320))
    dimensions = [0.09, 0.06, 0.03]
    for split, velocity, points in (("fit", 0.27, POINTS), ("held_out", 0.43, POINTS + [0.02, 0.01, 0.04])):
        t = np.linspace(0, 1, 101)
        moving = np.minimum(t, velocity / (0.2 * 9.81))
        xyz = np.column_stack([velocity * moving - 0.5 * 0.2 * 9.81 * moving**2,
                               np.zeros_like(t), np.full_like(t, dimensions[2] / 2)])
        write_new(output / f"{split}.json", json_bytes(dict(
            kind="synthetic", source="ideal Coulomb slide and known pinhole projection; generated by validate.py",
            split=split, velocity_m_s=velocity, dimensions_m=dimensions, points_m=points.tolist(),
            pixels=view.project(points)[0].tolist(), view=view.to_dict(), time_s=t.tolist(), xyz_m=xyz.tolist())))


def refine(fit_path):
    """Only the development file is available here; reserved observations are loaded after fitting."""
    fit = json.loads(fit_path.read_text())
    observation = Observation("development", fit_path, fit["source"], "synthetic", "fit",
                              dict(frame="base", image_transform="none", time_offset_s=0.0))
    view = fit_camera(observation, fit["points_m"], fit["pixels"], (480, 320), focal=fit["view"]["fx"])
    scores = []
    for friction in np.linspace(0.1, 0.4, 31):
        samples, _ = slide(fit["dimensions_m"], friction, fit["velocity_m_s"])
        predicted_x = np.interp(fit["time_s"], samples[:, 0], samples[:, 1])
        scores.append((float(np.mean((predicted_x - np.array(fit["xyz_m"])[:, 0])**2)), float(friction)))
    return dict(dimensions_m=fit["dimensions_m"], friction=min(scores)[1], view=view.to_dict(),
                mass_kg=0.1, timestep_s=0.001, solver_iterations=100, integrator="implicitfast",
                cone="elliptic", solref=[0.005, 1], fitting_observations=["fit.json"], mujoco_version=mj.__version__)


def compare_synthetic(output, reference, parameters):
    observations = [Observation(split, reference / f"{split}.json", "generated ideal Coulomb reference",
                                "synthetic", split,
                                dict(frame="base", image_transform="none", time_offset_s=0.0))
                    for split in ("fit", "held_out")]
    validation = Validation(output, scene=scene_identity({"validate.py": Path(__file__)}, parameters),
                            observations=observations, tolerances=LIMITS)
    view = View.from_dict(parameters["view"])
    for observation in observations:
        ref = json.loads(observation.path.read_text())
        validation.landmarks(observation.name, view, ref["points_m"], ref["pixels"])
        validation.dimensions(observation.name, ref["dimensions_m"], parameters["dimensions_m"],
                              labels=["block.width", "block.depth", "block.height"])
        samples, stability = slide(parameters["dimensions_m"], parameters["friction"], ref["velocity_m_s"])
        validation.motion(observation.name, ref["time_s"], ref["xyz_m"], samples[:, 0], samples[:, 1:4])
        validation.stability(observation.name, **stability)
        validation.images(observation.name, projection(View.from_dict(ref["view"]), ref["points_m"]),
                          projection(view, ref["points_m"]))
    return validation.finish()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=False)
    write_new(args.output / "source" / "validate.py", Path(__file__).read_bytes())
    reference = args.output / "reference"
    generate_reference(reference)
    initial = dict(dimensions_m=[0.12, 0.08, 0.04], friction=0.5,
                   view=View.look_at([0.6, -0.5, 0.6], [0, 0, 0.1], size=(480, 320)).to_dict(),
                   mass_kg=0.1, timestep_s=0.001, solver_iterations=100, integrator="implicitfast",
                   cone="elliptic", solref=[0.005, 1], fitting_observations=[], mujoco_version=mj.__version__)
    # Freeze refinement before either held-out comparison is inspected.
    refined = refine(reference / "fit.json")
    write_new(args.output / "refined-parameters.json", json_bytes(refined))
    reports = {name: compare_synthetic(args.output / name, reference, parameters)
               for name, parameters in (("initial", initial), ("refined", refined))}
    print(json.dumps({name: dict(status=report["status"], held_out={
        group: values["held_out"]["status"] for group, values in report["groups"].items()})
        for name, report in reports.items()}, indent=2))


if __name__ == "__main__":
    main()
